export function buildSeedListings(now: Date = new Date()): NewListing[] {
  return SEED_TEMPLATES.map(({ postedDaysAgo, ...template }) => ({
    ...template,
    amenities: { ...template.amenities },
    posted_at: new Date(
      now.getTime() - postedDaysAgo * 24 * 60 * 60 * 1000
    ).toISOString(),
  }));
}

